// Generates mods/index.js: one import per bundled mod folder (mods/<id>/index.js), sorted by id.
// Folders starting with "_" or "." (e.g. _template) are skipped. Run with `npm run mods`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = '// GENERATED by tools/mods-index.mjs (`npm run mods`). Do not edit by hand.\n'
  + '// The bundled mods, sorted by id. The registry (web/src/engine/mod/registry.js) is the only engine file that reads this.\n';

/** Mod folder names under <root>/mods that have an index.js, sorted, skipping names starting with _ or . */
export function listModDirs(root) {
  const dir = join(root, 'mods');
  return readdirSync(dir, { withFileTypes: true })
    .filter(e => e.isDirectory() && !/^[_.]/.test(e.name) && existsSync(join(dir, e.name, 'index.js')))
    .map(e => e.name)
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

const ident = id => 'mod_' + id.replace(/[^A-Za-z0-9_$]/g, '_');

/** The exact text of mods/index.js for the mods under root. */
export function renderModsIndex(root) {
  const ids = listModDirs(root);
  const imports = ids.map(id => `import ${ident(id)} from './${id}/index.js';`).join('\n');
  return `${HEADER}${imports}\n\nexport default [${ids.map(ident).join(', ')}];\n`;
}

/** Writes mods/index.js; returns true when the file changed. */
export function writeModsIndex(root) {
  const file = join(root, 'mods', 'index.js');
  const next = renderModsIndex(root);
  const prev = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (prev === next) return false;
  writeFileSync(file, next);
  return true;
}

