// Integration: window glows in the real pipeline (toWorldInput -> buildWorld -> sim -> renderer -> lighting) and
// decals without art draw nothing; every static model in the fixture worlds rasterises (explicit allow-list).
import test from 'node:test';
import assert from 'node:assert/strict';
import './support/ensure-mods-index.mjs';
import { createSim } from '../web/src/engine/sim/world-sim.js';
import { loadFixture, makeView } from './engine-support/world-views.mjs';
import { createRenderer } from '../web/src/engine/render/renderer.js';
import { createLighting } from '../web/src/engine/render/lighting.js';
// mods/index.js is generated by ensure-mods-index, so the registry loads after it ran
const { buildWorld } = await import('../web/src/engine/world/build.js');
const { resolveMod } = await import('../web/src/engine/mod/registry.js');
const { toWorldInput } = await import('../web/src/engine/mod/input.js');
import * as RASTER from '../web/src/engine/art/raster.js';

// classic art modules (iso.js, props-art.js, ui.js) touch browser globals at import
globalThis.matchMedia ??= () => ({ matches: false, addEventListener() {}, addListener() {} });
const STATIC = new Set(['building', 'prop', 'tree', 'venue', 'token', 'decal']);
// Non-decal models that may legitimately fail to raster in this node harness (none known).
const ALLOW = new Set([]);

function fixtureWorld(name) {
  const fx = loadFixture(name + '.json');
  if (!fx) return null;
  const mod = resolveMod();
  const { input, serverId } = toWorldInput(makeView(fx, { now: fx.now, demo: !!fx.demo }), { seed: 7 });
  const world = buildWorld(input, { v: 1, seed: 7, blocks: {}, lots: {} }, { mod, now: fx.now, seed: 7, serverId });
  return { fx, mod, input, world, serverId };
}

class FakeCanvas {
  constructor(w = 1, h = 1) { this.width = w; this.height = h; this.style = {}; }
  getContext() {
    const c = this;
    const img = (w, h) => ({ data: new Uint8ClampedArray(Math.max(1, w * h) * 4).fill(255), width: w, height: h });
    return new Proxy({}, { get: (t, k) => (k === 'getImageData' ? (x, y, w, h) => img(w, h) : k === 'createImageData' ? (w, h) => img(w?.width ?? w, w?.height ?? h)
      : k === 'canvas' ? c : k === 'measureText' ? () => ({ width: 0 }) : k in t ? t[k] : () => {}), set: (t, k, v) => { t[k] = v; return true; } });
  }
  toDataURL() { return ''; }
}
const fakeCanvas = (w, h) => new FakeCanvas(w, h);
globalThis.ImageData ??= class { constructor(d, w, h) { if (typeof d === 'number') { h = w; w = d; d = new Uint8ClampedArray(w * h * 4); } this.data = d; this.width = w; this.height = h ?? d.length / 4 / w; } };
globalThis.document ??= { createElement: () => new FakeCanvas() };

test('rasterising every static model of busy / harbour-6 / citydemo does not fail (decals excepted by name)', async () => {
  RASTER.setCanvasFactory(fakeCanvas);
  await RASTER.loadClassicArt();
  const failedModels = new Map();
  for (const name of ['busy', 'harbour-6', 'citydemo']) {
    const f = fixtureWorld(name);
    if (!f) continue;
    for (const o of f.world.objects.values()) {
      if (!STATIC.has(o.kind)) continue;
      const k = `${o.kind}:${o.model}`;
      let r = null;
      try { r = RASTER.rasterize(o.model, null, { kind: o.kind === 'building' ? 'building' : 'prop', variant: o.variant, w: o.w, h: o.h, scale: 1, anim: 0 }); } catch { r = null; }
      if (!r || !r.img) failedModels.set(k, name);
    }
  }
  const unexpected = [...failedModels.keys()].filter(k => !k.startsWith('decal:') && !ALLOW.has(k));
  assert.deepEqual(unexpected, [], 'non-decal models that fail to raster');
  console.log('decal models without art:', [...failedModels.keys()].filter(k => k.startsWith('decal:')).join(', '));
});

test('a decal that fails to raster draws nothing and is reported in stats().sprites.failedKeys', () => {
  const imgs = [];
  const gfx = { begin() {}, clear() {}, end() {}, image(...a) { imgs.push(a); }, rect() {}, poly() {}, setComposite() {}, size: () => ({ w: 800, h: 600 }) };
  const deps = {
    rasterize: () => null, loadClassicArt: async () => {}, createGround: () => ({ drawChunks() {} }),
    createLighting: () => ({ setTime() {}, lights: () => [], draw() {} }), createXray: () => ({ occluded: () => false, fadeFor: () => 1, draw() {} }),
    effects: { draw() {} }, badges: { draw() {} },
  };
  const r = createRenderer({ canvas: {}, gfx, mod: {}, deps });
  const mkO = (id, kind, model, tx) => ({ id, kind, model, tx, ty: 0, w: 1, h: 1, z: kind === 'decal' ? 0 : 20, walk: kind === 'decal' ? 'floor' : 'block', styleKey: 's', variant: 0 });
  r.setWorld({ objects: new Map([['d', mkO('d', 'decal', 'flowers', 0)], ['p', mkO('p', 'prop', 'nonesuch', 1)]]), version: 1 });
  const fr = { cam: { x: 0, y: 0, z: 1 }, view: { cssW: 800, cssH: 600, dpr: 1 }, actors: [], t: 0, night: 0, mode: 'town' };
  return (async () => {
    for (let i = 0; i < 5; i++) { await new Promise(r => setTimeout(r, 5)); r.draw(fr); }
    const keys = r.stats().sprites.failedKeys;
    assert.ok(keys.includes('decal:flowers'), JSON.stringify(keys));
    assert.ok(keys.length <= 20);
    // the prop draws its placeholder, the decal nothing: drop the prop and nothing is drawn at all
    imgs.length = 0; r.draw(fr);
    assert.ok(imgs.length > 0);
    r.setWorld({ objects: new Map([['d', mkO('d', 'decal', 'flowers', 0)]]), version: 2 });
    for (let i = 0; i < 3; i++) { await new Promise(r => setTimeout(r, 5)); r.draw(fr); }
    imgs.length = 0; r.draw(fr);
    assert.equal(imgs.length, 0);
  })();
});

test('busy fixture: resting homes glow at night in the real pipeline, working homes do not', async () => {
  RASTER.setCanvasFactory(fakeCanvas);
  await RASTER.loadClassicArt();
  const f = fixtureWorld('busy');
  assert.ok(f, 'busy fixture');
  const { world, input, mod, serverId } = f;
  const sim = createSim({ world, nav: null, seed: 7, mod: null, serverId });
  sim.applySnapshot({ apiVersion: 1, now: f.fx.now, seed: 7, agents: input.agents, projects: input.projects ?? [], prs: input.prs ?? [], env: { night: 1, reduceMotion: true, zoom: 1 } });
  sim.tick(0.05);
  const actors = [...sim.actors.values()].filter(a => a.kind === 'agent');
  assert.ok(actors.length > 0);
  const homes = new Map([...world.objects.values()].filter(o => o.kind === 'building' && o.data?.owner === 'home').map(o => [o.id, o]));
  const restingHomes = new Set(actors.filter(a => (a.input?.status ?? a.status?.bucket) === 'resting' && homes.has(a.home)).map(a => a.home));
  assert.ok(restingHomes.size > 0, 'some resting agent has a home');

  let lights = [];
  const gfx = { begin() {}, clear() {}, end() {}, image() {}, rect() {}, poly() {}, setComposite() {}, size: () => ({ w: 800, h: 600 }) };
  const deps = {
    createLighting: ({ world, statusOf }) => { const L = createLighting({ world, statusOf, createCanvas: fakeCanvas }); return { setTime: t => L.setTime(t), lights(o, a, w) { lights = L.lights(o, a, w); return lights; }, draw() {} }; },
  };
  const r = createRenderer({ canvas: {}, gfx, mod, deps });
  r.setWorld(world);
  // frame over the town: aim the camera at the first home
  const h0 = homes.get([...restingHomes][0]);
  const fr = { cam: { x: h0.tx, y: h0.ty, z: 1 }, view: { cssW: 1600, cssH: 1200, dpr: 1 }, actors, t: 0, night: 1, mode: 'town' };
  for (let i = 0; i < 8; i++) { await new Promise(r => setTimeout(r, 5)); r.draw(fr); }
  const win = lights.filter(l => l.kind === 'window');
  console.log('window lights:', win.length, 'resting homes:', restingHomes.size);
  assert.ok(win.length > 0, 'window lights in the real pipeline');
  const lit = new Set(win.map(l => l.id.split('#')[0]));
  for (const id of lit) assert.ok(restingHomes.has(id), `${id} lit but its agent is not resting`);
  assert.ok(lit.has(h0.id));
});
